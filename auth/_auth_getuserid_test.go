// contextWithToken creates a context with the specified token in the authorization metadata.
func contextWithToken(tokenString string) context.Context {
	ctx := context.Background()
	ctx = grpc_auth.AddToken(ctx, tokenString)
	return ctx
}

// generateToken generates a JWT token with the specified claims.
func generateToken(userID uint, exp time.Time, claims ...string) string {
	jwtSecret := []byte(os.Getenv("JWT_SECRET"))
	c := claims
	if len(c) == 0 {
		c = []string{"claims"}
	}
	token := jwt.NewWithClaims(jwt.SigningMethodHS256, &claims{
		UserID: userID,
		StandardClaims: jwt.StandardClaims{
			ExpiresAt: exp.Unix(),
		},
	})
	tokenString, err := token.SignedString(jwtSecret)
	if err != nil {
		panic(fmt.Sprintf("Error generating token: %v", err))
	}
	return tokenString
}
